import { useState } from "react";
import { LineChart, Line, XAxis, YAxis, Tooltip, CartesianGrid, ResponsiveContainer } from "recharts";
import "./App.css";
import Landing from "./Landing";

const API = "http://localhost:5000/api/quiz";

async function post(path, body) {
  const res = await fetch(API + path, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  const data = await res.json();
  if (!res.ok) throw new Error(data.error || "Something went wrong");
  return data;
}

export default function App() {
  const [stage, setStage] = useState("landing");
  const [topic, setTopic] = useState("");
  const [count, setCount] = useState(8);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [sessionId, setSessionId] = useState(null);
  const [question, setQuestion] = useState(null);
  const [qNo, setQNo] = useState(1);
  const [total, setTotal] = useState(0);
  const [ability, setAbility] = useState(3);
  const [selected, setSelected] = useState(null);
  const [feedback, setFeedback] = useState(null);
  const [result, setResult] = useState(null);

  async function startQuiz() {
    if (!topic.trim()) return setError("Please enter a topic");
    setError("");
    setLoading(true);
    try {
      const d = await post("/start", { topic, count });
      setSessionId(d.sessionId);
      setQuestion(d.question);
      setTotal(d.total);
      setAbility(d.ability);
      setQNo(1);
      setSelected(null);
      setFeedback(null);
      setStage("quiz");
    } catch (e) {
      setError(e.message);
    }
    setLoading(false);
  }

  async function choose(i) {
    if (feedback || loading) return;
    setSelected(i);
    setLoading(true);
    try {
      const d = await post("/answer", { sessionId, selectedIndex: i });
      setFeedback(d);
      setAbility(d.ability);
    } catch (e) {
      setError(e.message);
    }
    setLoading(false);
  }

  function next() {
    if (feedback.finished) {
      setResult(feedback.result);
      setStage("result");
    } else {
      setQuestion(feedback.question);
      setQNo(qNo + 1);
      setSelected(null);
      setFeedback(null);
    }
  }

  function restart() {
    setStage("landing");
    setResult(null);
    setFeedback(null);
    setSelected(null);
    setTopic("");
  }

  const optClass = (i) => {
    if (!feedback) return "opt";
    if (i === feedback.correctIndex) return "opt correct";
    if (i === selected && !feedback.correct) return "opt wrong";
    return "opt";
  };

  if (stage === "landing") return <Landing onStart={() => setStage("start")} />;

  return (
    <div className="app">
      <h1>AI-Powered Adaptive Quiz</h1>
      <p className="sub">Questions generated by AI. Difficulty adapts to you.</p>

      {stage === "start" && (
        <div className="card">
          <label>Topic</label>
          <input
            value={topic}
            onChange={(e) => setTopic(e.target.value)}
            placeholder="e.g. Operating Systems, DBMS, Photosynthesis"
          />
          <label>Number of questions: {count}</label>
          <input type="range" min="5" max="12" value={count} onChange={(e) => setCount(Number(e.target.value))} />
          <button onClick={startQuiz} disabled={loading}>
            {loading ? "Generating quiz with AI..." : "Start Quiz"}
          </button>
          {error && <div className="err">{error}</div>}
        </div>
      )}

      {stage === "quiz" && question && (
        <div className="card">
          <div className="meta">
            <span>Question {qNo} of {total}</span>
            <span>
              Difficulty <span className="badge">{question.difficulty}/5</span> &nbsp; Your ability{" "}
              <span className="badge">{ability}</span>
            </span>
          </div>
          <h3>{question.question}</h3>
          {question.options.map((o, i) => (
            <button key={i} className={optClass(i)} onClick={() => choose(i)} disabled={!!feedback}>
              {String.fromCharCode(65 + i)}. {o}
            </button>
          ))}
          {feedback && (
            <>
              <div className="fb">
                <b>{feedback.correct ? "Correct!" : "Wrong."}</b> {feedback.explanation}
                <br />
                Ability updated to <b>{feedback.ability}</b>
              </div>
              <button style={{ marginTop: 14 }} onClick={next}>
                {feedback.finished ? "See Result" : "Next Question"}
              </button>
            </>
          )}
          {error && <div className="err">{error}</div>}
        </div>
      )}

      {stage === "result" && result && (
        <div className="card">
          <h2>Result: {result.score} / {result.total}</h2>
          <p>Topic: <b>{result.topic}</b> &nbsp;|&nbsp; Final ability level: <b>{result.finalAbility}</b> / 5</p>
          <div style={{ height: 240 }}>
            <ResponsiveContainer>
              <LineChart
                data={[{ q: 0, ability: 3 }, ...result.history.map((h, i) => ({ q: i + 1, ability: h.abilityAfter }))]}
              >
                <CartesianGrid strokeDasharray="3 3" />
                <XAxis dataKey="q" label={{ value: "Question", position: "insideBottom", offset: -2 }} />
                <YAxis domain={[1, 5]} />
                <Tooltip />
                <Line type="monotone" dataKey="ability" stroke="#028090" strokeWidth={3} />
              </LineChart>
            </ResponsiveContainer>
          </div>
          <table>
            <thead>
              <tr><th>#</th><th>Question</th><th>Diff.</th><th></th></tr>
            </thead>
            <tbody>
              {result.history.map((h, i) => (
                <tr key={i}>
                  <td>{i + 1}</td>
                  <td>{h.question}</td>
                  <td>{h.difficulty}</td>
                  <td>{h.correct ? "✓" : "✗"}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <button style={{ marginTop: 16 }} onClick={restart}>Take another quiz</button>
        </div>
      )}
    </div>
  );
}